"""Build the index tables of docs/devlog/README.md and docs/decisions/README.md.

    uv run python scripts/gen_devlog_index.py          # rewrite both tables
    uv run python scripts/gen_devlog_index.py --check  # exit 1 if one is out of date

Each table sits between the two MARKERS in its README; everything outside them
is hand-written. The rows come from the entry files themselves, so two PRs that
each add an entry don't edit the same README line. tests/test_devlog_index.py
runs the check in CI.

What an entry needs (see the READMEs):

- Devlog: a file `docs/devlog/YYYY-MM-DD-short-title.md` (the date comes from the
  name), a `# Title` heading, an `**Area:** ...` field in its header line, and one
  metadata comment, for example:

      <!-- index | refs: #5, PR #28 -->

- ADR: a file `docs/decisions/NNNN-short-title.md`, a `# NNNN. Title` heading,
  `- **Status:** ...` and `- **Date:** YYYY-MM-DD` lines, and the same comment.

`refs` is the "Issues / PRs" cell and is required. Optional keys override what
is read from the entry: `title`, `area` (devlog), `status` (ADR); for example
`<!-- index | refs: #44 | area: UI design -->`. Values can't contain `|`.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path
from typing import NamedTuple

ROOT = Path(__file__).resolve().parent.parent
DEVLOG = ROOT / "docs" / "devlog"
DECISIONS = ROOT / "docs" / "decisions"
BEGIN = "<!-- index:begin (generated by scripts/gen_devlog_index.py; don't edit by hand) -->"
END = "<!-- index:end -->"

DEVLOG_NAME = re.compile(r"^(\d{4}-\d{2}-\d{2})-.+\.md$")
ADR_NAME = re.compile(r"^(\d{4})-.+\.md$")
METADATA = re.compile(r"^<!--\s*index\s*\|(.*?)-->\s*$", re.MULTILINE)
HEADING = re.compile(r"^# (.+?)\s*$", re.MULTILINE)
AREA = re.compile(r"\*\*Area:\*\*\s*([^·\n]+?)\s*(?:·|$)", re.MULTILINE)
STATUS = re.compile(r"^- \*\*Status:\*\*\s*(.+?)\s*$", re.MULTILINE)
DATE = re.compile(r"^- \*\*Date:\*\*\s*(\d{4}-\d{2}-\d{2})", re.MULTILINE)


class EntryError(ValueError):
    """An entry lacks something the index needs."""


class Entry(NamedTuple):
    path: Path
    fields: dict[str, str]


def read_metadata(path: Path, text: str) -> dict[str, str]:
    """The `<!-- index | key: value | ... -->` comment as a dict."""
    match = METADATA.search(text)
    if match is None:
        raise EntryError(
            f"{path.name}: no metadata comment; add a line like "
            "'<!-- index | refs: #N, PR #M -->'"
        )
    fields = {}
    for part in match.group(1).split("|"):
        if not part.strip():
            continue
        key, sep, value = part.partition(":")
        if not sep:
            raise EntryError(
                f"{path.name}: metadata part {part.strip()!r} is not 'key: value'"
            )
        fields[key.strip().lower()] = value.strip()
    if not fields.get("refs"):
        raise EntryError(f"{path.name}: the metadata comment needs 'refs: ...'")
    return fields


def _first(pattern: re.Pattern, text: str, path: Path, what: str) -> str:
    match = pattern.search(text)
    if match is None:
        raise EntryError(f"{path.name}: no {what} found")
    return match.group(1).strip()


def devlog_entries(folder: Path = DEVLOG) -> list[Entry]:
    entries = []
    for path in sorted(folder.glob("*.md")):
        name = DEVLOG_NAME.match(path.name)
        if name is None:
            continue
        text = path.read_text(encoding="utf-8")
        meta = read_metadata(path, text)
        fields = {
            "date": name.group(1),
            "title": meta.get("title")
            or _first(HEADING, text, path, "'# Title' heading"),
            "area": meta.get("area") or _first(AREA, text, path, "'**Area:**' field"),
            "refs": meta["refs"],
        }
        entries.append(Entry(path, fields))
    return sorted(entries, key=lambda e: (e.fields["date"], e.path.name))


def adr_entries(folder: Path = DECISIONS) -> list[Entry]:
    entries = []
    for path in sorted(folder.glob("*.md")):
        name = ADR_NAME.match(path.name)
        if name is None:
            continue
        text = path.read_text(encoding="utf-8")
        meta = read_metadata(path, text)
        number = name.group(1)
        title = meta.get("title") or _first(
            HEADING, text, path, "'# NNNN. Title' heading"
        )
        title = re.sub(rf"^{number}\.\s*", "", title)
        # "Accepted (implementation in PR #64, ...)" lists as "Accepted".
        status = meta.get("status") or _first(
            STATUS, text, path, "'- **Status:**' line"
        )
        status = status.split(" (")[0].strip()
        fields = {
            "number": number,
            "title": title,
            "status": status,
            "date": _first(DATE, text, path, "'- **Date:**' line"),
            "refs": meta["refs"],
        }
        entries.append(Entry(path, fields))
    return sorted(entries, key=lambda e: e.fields["number"])


def render_devlog(entries: list[Entry]) -> str:
    lines = ["| Date | Title | Area | Issues / PRs |", "|---|---|---|---|"]
    for e in entries:
        f = e.fields
        lines.append(
            f"| {f['date']} | [{f['title']}]({e.path.name}) | {f['area']} | {f['refs']} |"
        )
    return "\n".join(lines)


def render_adrs(entries: list[Entry]) -> str:
    lines = [
        "| # | Title | Status | Date | Issues / PRs |",
        "|---|---|---|---|---|",
    ]
    for e in entries:
        f = e.fields
        lines.append(
            f"| [{f['number']}]({e.path.name}) | {f['title']} | {f['status']} "
            f"| {f['date']} | {f['refs']} |"
        )
    return "\n".join(lines)


def updated_readme(text: str, table: str) -> str:
    start, end = text.index(BEGIN), text.index(END)
    return text[: start + len(BEGIN)] + "\n" + table + "\n" + text[end:]


def targets() -> list[tuple[Path, str]]:
    """Each README with the table it should hold."""
    return [
        (DEVLOG / "README.md", render_devlog(devlog_entries())),
        (DECISIONS / "README.md", render_adrs(adr_entries())),
    ]


def main() -> int:
    check = "--check" in sys.argv
    try:
        wanted = targets()
    except EntryError as error:
        print(f"error: {error}")
        return 1
    stale = []
    for readme, table in wanted:
        text = readme.read_text(encoding="utf-8")
        new = updated_readme(text, table)
        if new == text:
            continue
        stale.append(readme.relative_to(ROOT).as_posix())
        if not check:
            readme.write_text(new, encoding="utf-8")
    if check and stale:
        print(", ".join(stale) + " out of date: run scripts/gen_devlog_index.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
