"""Build CREDITS.md's asset section from assets/SOURCES.yaml.

    uv run python scripts/gen_credits.py          # rewrite the section
    uv run python scripts/gen_credits.py --check  # exit 1 if it is out of date

The section sits between the two MARKERS in CREDITS.md; everything outside
them is hand-written. tests/test_sources.py runs the check, so the credits
can't drift from the data.
"""

from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "assets" / "SOURCES.yaml"
CREDITS = ROOT / "CREDITS.md"
BEGIN = "<!-- assets:begin (generated by scripts/gen_credits.py from assets/SOURCES.yaml) -->"
END = "<!-- assets:end -->"
LICENSE_LINKS = {
    "CC0-1.0": "[CC0 1.0](https://creativecommons.org/publicdomain/zero/1.0/)",
}
REPO_SOURCES = "https://github.com/vectorviolet/highrise/blob/main/assets/SOURCES.yaml"


def load_sources(path: Path = SOURCES) -> dict:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def render(data: dict) -> str:
    packs, files = data["packs"], data["files"]
    counts = Counter(entry["source"] for entry in files.values())
    lines = [
        "## Assets",
        "",
        "| Pack | Author | License | Used for | Files |",
        "|---|---|---|---|---|",
    ]
    for slug in sorted(packs, key=lambda s: (-counts[s], s)):
        pack = packs[slug]
        lines.append(
            f"| [{pack['name']}]({pack['url']}) | {pack['author']} "
            f"| {LICENSE_LINKS.get(pack['license'], pack['license'])} "
            f"| {pack['used_for']} | {counts[slug]} |"
        )
    own = sorted(rel for rel, entry in files.items() if entry["source"] == "own")
    lines += [""]
    if own:
        lines += [
            "Made for this game by its developer: "
            + ", ".join(rel.split("/")[-1] for rel in own)
            + " (in assets/"
            + ", assets/".join(rel.rsplit("/", 1)[0] for rel in own)
            + ").",
            "",
        ]
    lines += [
        "CC0 assets need no attribution; they are credited here anyway. Each pack's own",
        "license text ships with the game: "
        + ", ".join(f"`licenses/assets/{slug}.txt`" for slug in sorted(packs))
        + ".",
        f"[assets/SOURCES.yaml]({REPO_SOURCES}) in the source repository lists every asset",
        "file with its pack and its original file name there.",
    ]
    return "\n".join(lines)


def updated_credits(text: str, section: str) -> str:
    start, end = text.index(BEGIN), text.index(END)
    return text[: start + len(BEGIN)] + "\n" + section + "\n" + text[end:]


def main() -> int:
    text = CREDITS.read_text(encoding="utf-8")
    new = updated_credits(text, render(load_sources()))
    if "--check" in sys.argv:
        if new != text:
            print("CREDITS.md is out of date: run scripts/gen_credits.py")
            return 1
        return 0
    CREDITS.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
